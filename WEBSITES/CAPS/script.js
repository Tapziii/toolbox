let currentLang = 'en';

const textInput = document.getElementById('textInput');
const langSwitcher = document.getElementById('langSwitcher');
const toast = document.getElementById('toast');

// Stats
const charCountEl = document.getElementById('charCount');
const wordCountEl = document.getElementById('wordCount');
const lineCountEl = document.getElementById('lineCount');

// Update UI Language
function updateLanguage(lang) {
    currentLang = lang;
    const dict = i18n[lang];
    
    document.documentElement.setAttribute('dir', dict.dir);
    document.documentElement.setAttribute('lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.textContent = dict[key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.placeholder = dict[key];
        }
    });
}

langSwitcher.addEventListener('change', (e) => {
    updateLanguage(e.target.value);
});

// Stats Update
function updateStats() {
    const text = textInput.value;
    
    charCountEl.textContent = text.length;
    lineCountEl.textContent = text.length === 0 ? 0 : text.split('\n').length;
    
    const words = text.trim().split(/\s+/).filter(word => word.length > 0);
    wordCountEl.textContent = text.trim() === '' ? 0 : words.length;
}

textInput.addEventListener('input', updateStats);

// Toast Notification
function showToast(messageKey) {
    toast.textContent = i18n[currentLang][messageKey];
    toast.classList.add('show');
    setTimeout(() => {
        toast.classList.remove('show');
    }, 2500);
}

// Actions
document.getElementById('btnCopy').addEventListener('click', () => {
    if (textInput.value) {
        navigator.clipboard.writeText(textInput.value).then(() => {
            showToast('toastCopied');
        });
    }
});

document.getElementById('btnShare').addEventListener('click', async () => {
    if (navigator.share && textInput.value) {
        try {
            await navigator.share({
                title: 'Text Case Converter',
                text: textInput.value,
            });
        } catch (err) {
            console.error('Error sharing:', err);
        }
    }
});

document.getElementById('btnDownload').addEventListener('click', () => {
    if (!textInput.value) return;
    
    const blob = new Blob([textInput.value], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'converted_text.txt';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    showToast('toastDownloaded');
});

document.getElementById('btnClear').addEventListener('click', () => {
    textInput.value = '';
    updateStats();
    showToast('toastCleared');
});

// Format Conversions
function convertText(conversionType) {
    const text = textInput.value;
    if (!text) return;
    
    let result = '';
    
    switch (conversionType) {
        case 'sentence':
            result = text.toLowerCase().replace(/(^\s*\w|[\.\!\?]\s*\w)/g, c => c.toUpperCase());
            break;
        case 'lower':
            result = text.toLowerCase();
            break;
        case 'upper':
            result = text.toUpperCase();
            break;
        case 'capitalized':
            result = text.toLowerCase().replace(/\b\w/g, c => c.toUpperCase());
            break;
        case 'title':
            const smallWords = /^(a|an|and|as|at|but|by|en|for|if|in|nor|of|on|or|per|the|to|v.?|vs.?|via)$/i;
            result = text.toLowerCase().split(/\s+/).map((word, index, arr) => {
                if (index === 0 || index === arr.length - 1 || !smallWords.test(word) || word.includes('-')) {
                    return word.charAt(0).toUpperCase() + word.slice(1);
                }
                return word;
            }).join(' ');
            
            // Handle newlines correctly
            result = text.split('\n').map(line => {
                return line.toLowerCase().split(/\s+/).map((word, index, arr) => {
                    if (index === 0 || index === arr.length - 1 || !smallWords.test(word)) {
                        return word.charAt(0).toUpperCase() + word.slice(1);
                    }
                    return word;
                }).join(' ');
            }).join('\n');
            break;
        case 'inverse':
            result = text.split('').map(c => {
                return c === c.toUpperCase() ? c.toLowerCase() : c.toUpperCase();
            }).join('');
            break;
        case 'reverse':
            result = text.split('').reverse().join('');
            break;
    }
    
    textInput.value = result;
    updateStats();
}

document.getElementById('btnSentence').addEventListener('click', () => convertText('sentence'));
document.getElementById('btnLower').addEventListener('click', () => convertText('lower'));
document.getElementById('btnUpper').addEventListener('click', () => convertText('upper'));
document.getElementById('btnCapitalized').addEventListener('click', () => convertText('capitalized'));
document.getElementById('btnTitle').addEventListener('click', () => convertText('title'));
document.getElementById('btnInverse').addEventListener('click', () => convertText('inverse'));
document.getElementById('btnReverse').addEventListener('click', () => convertText('reverse'));

// Initial render
updateLanguage(currentLang);
